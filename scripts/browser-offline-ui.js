async (page) => {
  const mode = '__MODE__'
  const assert = (value, message) => { if (!value) throw new Error(message) }
  const panel = page.getByRole('complementary', { name: 'Dữ liệu và cập nhật' })
  const ready = () => page.waitForFunction(() => document.querySelector('.offline-panel')?.dataset.cachePhase === 'ready')
  const control = options => page.evaluate(options => fetch('/__test/control', { method: 'POST', body: JSON.stringify(options) }).then(r => r.json()), options)
  const update = () => page.evaluate(async () => { await (await navigator.serviceWorker.getRegistration()).update() })
  if (mode !== 'update') {
    await page.waitForFunction(() => document.querySelector('.offline-panel')?.dataset.cachePhase === 'error')
    assert(await page.evaluate(async () => !(await navigator.serviceWorker.getRegistration())?.active), 'Failed cache activated')
    if (mode === 'quota') {
      assert((await panel.textContent()).includes('dung lượng'), 'Quota guidance absent')
      await panel.getByRole('button', { name: 'Tải dữ liệu tiếng đàn', exact: true }).click()
      await page.getByRole('button', { name: 'Start Piano', exact: true }).click()
      await page.getByRole('status').filter({ hasText: 'Sẵn sàng chơi' }).waitFor()
      assert(await page.locator('button[data-note]:not(:disabled)').count() === 61, 'Quota failure disabled online piano')
      assert(await page.locator('.offline-panel').getAttribute('data-cache-phase') !== 'ready', 'Online audio falsely marked offline ready')
    }
    await control({ quota: false, corrupt: false })
    await panel.getByRole('button', { name: 'Tải dữ liệu tiếng đàn', exact: true }).click()
    await ready()
    await page.reload(); await ready()
    await page.evaluate(async () => {
      const names = await caches.keys(); const cache = await caches.open(names.find(name => name.startsWith('keyflow-piano-v1-')))
      const key = (await cache.keys()).find(key => key.url.includes('/C3.mp3'))
      const bytes = new Uint8Array(await (await cache.match(key)).arrayBuffer()); bytes[100] ^= 1
      await cache.put(key, new Response(bytes, { headers: { 'Content-Type': 'audio/mpeg' } }))
    })
    await page.evaluate(() => window.dispatchEvent(new Event('focus')))
    await page.waitForFunction(() => document.querySelector('.offline-panel')?.dataset.cachePhase === 'error')
    await panel.getByRole('button', { name: 'Tải dữ liệu tiếng đàn', exact: true }).click()
    await ready()
    await page.context().setOffline(true)
    await page.waitForFunction(() => !navigator.onLine)
    await page.evaluate(async () => {
      for (const name of await caches.keys()) if (name.startsWith('keyflow-piano-v1-')) {
        const cache = await caches.open(name)
        for (const key of await cache.keys()) if (key.url.includes('/C3.mp3')) await cache.delete(key)
      }
      window.dispatchEvent(new Event('focus'))
    })
    await page.waitForFunction(() => document.querySelector('.offline-panel')?.dataset.cachePhase === 'error')
    await panel.getByRole('button', { name: 'Tải dữ liệu tiếng đàn', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('.offline-panel')?.dataset.cachePhase === 'error')
    await page.context().setOffline(false)
    await panel.getByRole('button', { name: 'Tải dữ liệu tiếng đàn', exact: true }).click()
    await ready()
    assert((await page.locator('.audio-state').textContent()).includes('Bật âm thanh để bắt đầu'), 'Offline status started audio automatically')
    return { passed: true, firstFailureVisible: true, quotaGuidance: mode === 'quota', onlinePianoWithQuotaFailure: mode === 'quota', buttonRetry: true, corruptionRepair: true, evictionOfflineNotReady: true, onlineRecovery: true, noAutoAudio: true }
  }
  await ready(); await page.reload(); await ready()
  await page.getByRole('button', { name: 'Start Piano', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Sẵn sàng chơi' }).waitFor()
  await page.getByRole('heading', { name: 'Salamander Grand' }).click()
  await page.keyboard.down('z')
  await control({ version: 2, corrupt: true }); await update()
  await panel.getByText('Chưa tải được bản mới. Phiên hiện tại vẫn dùng được.', { exact: true }).waitFor()
  await ready()
  assert(await page.locator('button[data-note][aria-pressed=true]').count() === 1, 'Failed update interrupted held note')
  await control({ corrupt: false }); await update()
  const apply = panel.getByRole('button', { name: 'Cập nhật KeyFlow', exact: true })
  await apply.waitFor()
  assert(await apply.isDisabled(), 'Update enabled while note held')
  await page.keyboard.up('z')
  assert(await apply.isDisabled(), 'Update enabled during release tail')
  await page.waitForTimeout(1300)
  await page.getByRole('heading', { name: 'Salamander Grand' }).click()
  await page.keyboard.down('Space')
  assert(await apply.isDisabled(), 'Update enabled while pedal held')
  await page.keyboard.up('Space'); await page.waitForTimeout(1300)
  const other = await page.context().newPage(); await other.goto(page.url())
  await apply.click()
  await panel.getByText('Đóng các cửa sổ KeyFlow khác rồi thử cập nhật lại.', { exact: true }).waitFor()
  assert(await page.locator('button[data-note]:not(:disabled)').count() > 0, 'Blocked update failed to unlock input')
  await other.close()
  await page.getByRole('slider', { name: 'Âm lượng' }).focus()
  await page.keyboard.press('Home'); await page.keyboard.press('ArrowRight')
  await page.setViewportSize({ width: 1440, height: 1100 })
  await page.screenshot({ path: 'output/playwright/task502-offline-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile page overflow')
  await page.screenshot({ path: 'output/playwright/task502-offline-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Đóng lời nhắc xoay ngang' }).click()
  await apply.click()
  await page.locator('meta[name="ui-test-version"][content="2"]').waitFor({ state: 'attached' })
  await ready()
  assert(await page.getByRole('slider', { name: 'Âm lượng' }).inputValue() === '1', 'Update lost device settings')
  // Complete Cache Storage verification and in-memory sample preparation are
  // separate phases. Neither may autoplay; idle copy changes once bytes are ready.
  assert(await page.locator('button[data-note]:not(:disabled)').count() === 0, 'New build unlocked notes without Start')
  await page.waitForFunction(() => document.querySelector('.offline-panel')?.dataset.sampleStatus === 'ready')
  assert((await page.locator('.audio-state').textContent()).includes('Bật âm thanh để bắt đầu'), 'New build did not show Start-required audio state after data preparation')
  return { passed: true, badCandidatePreservesReadyAndHeldNote: true, heldPedalTailGate: true, multipleClientsBlocked: true, explicitQuietUpdateReloadsMatchingBuild: true, settingsPreserved: true, responsiveScreenshots: true, newBuildNeedsGesture: true }
}
