async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message) }
  const up = page.getByRole('button', { name: 'Octave cao hơn', exact: true })
  const down = page.getByRole('button', { name: 'Octave thấp hơn', exact: true })
  const group = page.getByRole('group', { name: 'Octave', exact: true })
  const held = () => page.locator('button[data-note][aria-pressed=true]')
  const defocus = () => page.getByRole('heading', { name: 'Salamander Grand' }).click()
  await defocus()
  await page.keyboard.down('z')
  await up.click()
  assert(await held().getAttribute('data-note') === 'C3', 'Octave changed an already held pitch')
  assert((await group.textContent()).includes('C4 — B5'), 'Octave range did not update')
  assert(await page.getByRole('button', { name: 'Nốt C4, phím Z', exact: true }).count() === 1, 'Piano key mapping label did not update')
  assert((await page.locator('.row-name').last().textContent()).includes('C4 — B4'), 'Guide octave did not update')
  await page.keyboard.up('z')
  assert(await held().count() === 0, 'Changed octave left the original note stuck')
  await defocus()
  await page.keyboard.down('z')
  assert(await held().getAttribute('data-note') === 'C4', 'New press did not use new octave')
  await page.keyboard.up('z')
  await up.click()
  assert(await up.isDisabled(), 'Upper octave boundary not disabled')
  await defocus()
  await page.keyboard.press('ArrowUp')
  assert((await group.textContent()).includes('C5 — B6'), 'Arrow exceeded upper octave boundary')
  await page.keyboard.down('u')
  assert(await held().getAttribute('data-note') === 'B6', 'Upper mapped note is wrong')
  await page.keyboard.up('u')
  for (let i = 0; i < 3; i++) await page.keyboard.press('ArrowDown')
  assert(await down.isDisabled() && (await group.textContent()).includes('C2 — B3'), 'Lower octave boundary not reached')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.down('z')
  assert(await held().getAttribute('data-note') === 'C2', 'Lower mapped note is wrong')
  await page.keyboard.up('z')
  await page.getByRole('slider', { name: 'Âm lượng' }).focus()
  await page.keyboard.press('ArrowUp')
  assert((await group.textContent()).includes('C2 — B3'), 'Octave intercepted range input arrows')
  await page.keyboard.press('End')
  await defocus()
  await page.keyboard.press('ArrowUp')
  assert((await group.textContent()).includes('C3 — B4'), 'Arrow did not restore default octave')
  return { passed: true, checks: ['Held pitch releases correctly across octave changes', 'New press, piano labels and guide use shifted mapping', 'UI and arrow shortcuts respect −1..+2 boundaries and C2/B6 endpoints', 'Focused range input keeps native arrows'], finalRange: 'C3 — B4' }
}
