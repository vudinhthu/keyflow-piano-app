async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message) }
  const key = 'keyflow-piano:settings'
  const slider = () => page.getByRole('slider', { name: 'Âm lượng' })
  const velocity = () => page.getByRole('combobox', { name: 'Sắc thái' })
  const octave = () => page.getByRole('group', { name: 'Octave', exact: true })
  const ready = () => page.getByRole('status').filter({ hasText: 'Sẵn sàng chơi' }).waitFor()
  const held = () => page.locator('button[data-note][aria-pressed=true]')
  const defocus = () => page.getByRole('heading', { name: 'Salamander Grand' }).click()
  const read = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)), key)
  await page.evaluate(key => localStorage.removeItem(key), key)
  await page.reload()
  await slider().focus()
  await page.keyboard.press('Home')
  for (let i = 0; i < 25; i++) await page.keyboard.press('ArrowRight')
  await page.getByRole('button', { name: 'Octave cao hơn', exact: true }).click()
  await velocity().selectOption('0.4')
  const chosen = await read()
  assert(JSON.stringify(chosen) === JSON.stringify({ version: 1, volume: 25, octaveShift: 1, velocity: 0.4 }), 'Selected settings were not saved')
  await page.getByRole('button', { name: 'Start Piano', exact: true }).click()
  await ready()
  await defocus()
  await page.keyboard.down('Space')
  await page.keyboard.down('z')
  await page.keyboard.up('z')
  await page.keyboard.down('x')
  assert(await held().count() === 1, 'Expected held note before reload')
  assert(JSON.stringify(await read()) === JSON.stringify(chosen), 'Notes or sustain changed persisted settings')
  await page.reload()
  await page.keyboard.up('x')
  await page.keyboard.up('Space')
  assert(await slider().inputValue() === '25', 'Reload lost volume')
  assert((await octave().textContent()).includes('C4 — B5'), 'Reload lost octave')
  assert(await velocity().inputValue() === '0.4', 'Reload lost velocity')
  assert(await held().count() === 0 && await page.locator('[data-sustained=true]').count() === 0, 'Reload restored note owners')
  assert(await page.locator('button[data-note]:not(:disabled)').count() === 0, 'Reload unlocked audio without a gesture')
  assert(await page.getByRole('button', { name: 'Sustain — giữ pedal', exact: true }).getAttribute('aria-pressed') === 'false', 'Reload restored pedal')
  await page.getByRole('button', { name: 'Start Piano', exact: true }).click()
  await ready()
  await defocus()
  const marker = await page.evaluate(() => window.__pianoAudio.connections.length)
  await page.keyboard.down('z')
  assert(await held().getAttribute('data-note') === 'C4', 'Restored octave not applied to real input')
  await page.waitForFunction(start => window.__pianoAudio.connections.slice(start).some(({ source, destination }) => source instanceof AudioBufferSourceNode && source.context.state === 'running' && destination instanceof GainNode && Math.abs(destination.gain.value - 0.4) < 0.00001), marker)
  await page.waitForTimeout(100)
  const rms = await page.evaluate(() => Math.max(0, ...window.__pianoAudio.analysers.map(a => { const v = new Float32Array(a.fftSize); a.getFloatTimeDomainData(v); return Math.sqrt(v.reduce((s, x) => s + x * x, 0) / v.length) })))
  assert(rms > 0.00001, 'No real audio after reload')
  await page.keyboard.up('z')
  await slider().focus()
  await page.keyboard.press('Home')
  await page.reload()
  assert(await slider().inputValue() === '0', 'Muted setting was not restored')
  await page.getByRole('button', { name: 'Start Piano', exact: true }).click()
  await ready()
  await defocus()
  await page.keyboard.down('z')
  await page.waitForTimeout(100)
  const muteRms = await page.evaluate(() => Math.max(0, ...window.__pianoAudio.analysers.map(a => { const v = new Float32Array(a.fftSize); a.getFloatTimeDomainData(v); return Math.sqrt(v.reduce((s, x) => s + x * x, 0) / v.length) })))
  assert(muteRms < 0.000001, 'Restored mute was not applied to audio')
  await page.keyboard.up('z')
  const corrupt = []
  for (const record of ['broken JSON', JSON.stringify({ version: 2, volume: 25 }), JSON.stringify({ version: 1, volume: -1, octaveShift: 3, velocity: '1' })]) {
    await page.evaluate(({ key, record }) => localStorage.setItem(key, record), { key, record })
    await page.reload()
    assert(await slider().inputValue() === '100' && await velocity().inputValue() === '0.72' && (await octave().textContent()).includes('C3 — B4'), 'Invalid stored data did not fall back')
    corrupt.push(record)
  }
  await page.evaluate(key => localStorage.setItem(key, JSON.stringify({ version: 1, volume: 60, octaveShift: 0.5, velocity: 1 })), key)
  await page.reload()
  assert(await slider().inputValue() === '60' && await velocity().inputValue() === '1' && (await octave().textContent()).includes('C3 — B4'), 'Per-field fallback discarded valid settings')
  // Fault injection is restricted to the disposable test page.
  await page.addInitScript(() => {
    const get = Storage.prototype.getItem
    const set = Storage.prototype.setItem
    Storage.prototype.getItem = function (key) { if (window.__storageFault === 'read') throw new DOMException('Blocked', 'SecurityError'); return get.call(this, key) }
    Storage.prototype.setItem = function (key, value) { if (window.__storageFault === 'quota') throw new DOMException('Full', 'QuotaExceededError'); return set.call(this, key, value) }
    window.__storageFault = 'read'
  })
  await page.reload()
  assert(await slider().inputValue() === '100', 'Denied storage read did not use defaults')
  await page.evaluate(() => { window.__storageFault = 'quota' })
  await slider().focus()
  await page.keyboard.press('Home')
  await page.keyboard.press('ArrowRight')
  assert(await slider().inputValue() === '1', 'Quota failure stopped settings interaction')
  await page.getByRole('button', { name: 'Start Piano', exact: true }).click()
  await ready()
  await defocus()
  await page.keyboard.down('z')
  assert(await held().count() === 1, 'Storage failure stopped playing')
  await page.keyboard.up('z')
  await page.evaluate(() => { window.__storageFault = null })
  await slider().focus()
  await page.keyboard.press('End')
  assert((await read()).volume === 100, 'Saving did not recover after storage fault')
  const errors = await page.evaluate(() => window.__pianoAudio.errors)
  assert(errors.length === 0, `Unexpected runtime errors: ${errors.join('; ')}`)
  return { passed: true, chosen, rmsAfterReload: rms, muteRms, corruptCases: corrupt.length, perFieldFallback: true, idleAfterReload: true, transientStateExcluded: true, restoredPitch: 'C4', restoredAttackVelocity: 0.4, deniedReadAndQuota: true, storageRecovered: true, runtimeErrors: errors }
}
