async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message) }
  const checks = []
  const add = (name) => checks.push(name)
  const pressed = () => page.locator('button[data-note][aria-pressed="true"]').count()
  const signal = () => page.evaluate(() => Math.max(0, ...window.__pianoAudio.analysers.map((analyser) => {
    const values = new Float32Array(analyser.fftSize)
    analyser.getFloatTimeDomainData(values)
    return Math.sqrt(values.reduce((sum, value) => sum + value * value, 0) / values.length)
  })))
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.getByRole('status').filter({ hasText: 'Sẵn sàng chơi' }).waitFor()
  assert(await page.locator('button[data-note]').count() === 61, '61 piano keys required')
  assert(await page.locator('.white-key').count() === 36 && await page.locator('.black-key').count() === 25, 'Incorrect piano layout')
  const samples = await page.evaluate(() => performance.getEntriesByType('resource').filter((entry) => entry.name.endsWith('.mp3')).length)
  const decoded = await page.evaluate(async () => {
    const expected = (await (await fetch('/samples/salamander/manifest.json')).json()).assets.map(asset => asset.bytes).sort((a,b) => a-b)
    const observed = window.__pianoAudio.decodedSizes.filter(size => expected.includes(size)).sort((a,b) => a-b)
    return { expected, observed }
  })
  assert(JSON.stringify(decoded.observed) === JSON.stringify(decoded.expected), 'Ready without all 21 pinned sample decodes')
  add('61 keys and all 21 local samples ready')

  await page.keyboard.down('z')
  await page.keyboard.down('c')
  await page.keyboard.down('b')
  assert(await pressed() === 3, 'Chord must have three held pitches')
  assert((await page.getByTestId('active-notes').textContent()).includes('C3 · E3 · G3'), 'Chord readout mismatch')
  await page.waitForTimeout(100)
  const chordRms = await signal()
  assert(chordRms > 0.0001, `No real audio signal: RMS ${chordRms}`)
  await page.screenshot({ path: 'output/playwright/phase1-desktop.png', fullPage: true })
  add('C3 E3 G3 chord generates a real Web Audio waveform and highlights')

  const beforeRepeat = await page.evaluate(() => window.__pianoAudio.sources)
  await page.keyboard.down('z')
  await page.keyboard.down('z')
  assert(await page.evaluate(() => window.__pianoAudio.sources) === beforeRepeat, 'Repeat created an audio source')
  assert(await pressed() === 3, 'Repeat duplicated a pitch')
  add('Repeated keydown does not create extra audio sources')
  for (const key of ['z', 'c', 'b']) await page.keyboard.up(key)
  assert(await pressed() === 0, 'Keyup did not clear UI')
  await page.waitForTimeout(500)
  const silenceRms = await signal()
  assert(silenceRms < 0.000001, `Released notes did not decay to silence: ${silenceRms}`)
  add('Keyup releases audio to silence')

  await page.keyboard.down('z')
  const key = page.getByRole('button', { name: 'Nốt C3, phím Z', exact: true })
  const box = await key.boundingBox()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height - 30)
  await page.mouse.down()
  await page.mouse.up()
  assert(await pressed() === 1, 'Pointer release cut a QWERTY-owned note')
  await page.keyboard.up('z')
  assert(await pressed() === 0, 'Shared note did not release')
  add('Pointer and keyboard share pitch ownership correctly')

  await page.keyboard.down('q')
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  assert(await pressed() === 0, 'Blur left a stuck note')
  await page.keyboard.up('q')
  await page.keyboard.down('q')
  assert(await pressed() === 1, 'Input did not recover after blur')
  await page.keyboard.up('q')
  add('Focus loss clears notes and allows a fresh press')

  // An injected fixture checks input routing, without adding a test control to the product UI.
  await page.evaluate(() => { const input = document.createElement('input'); input.id = 'qa-editable'; document.body.append(input); input.focus() })
  await page.keyboard.type('zxc')
  assert(await pressed() === 0, 'Typing in an input played the piano')
  await page.evaluate(() => document.getElementById('qa-editable').remove())
  add('Editable fields keep keyboard input')

  const allKeys = ['z','s','x','d','c','v','g','b','h','n','j','m','q','2','w','3','e','r','5','t','6','y','7','u']
  for (const code of allKeys) await page.keyboard.down(code)
  assert(await pressed() === 24, 'Full QWERTY mapping or simultaneous input failed')
  for (const code of allKeys) await page.keyboard.up(code)
  assert(await pressed() === 0, '24-key chord did not release')
  add('All 24 QWERTY positions can play simultaneously')

  await page.setViewportSize({ width: 390, height: 844 })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Page overflow on a narrow viewport')
  await page.screenshot({ path: 'output/playwright/phase1-mobile-layout.png', fullPage: true })
  add('Narrow layout scrolls piano internally without page overflow')
  await page.setViewportSize({ width: 1440, height: 1100 })
  await page.locator('.orientation-popup').waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: 'Nốt C4, phím Q', exact: true }).focus()
  await page.keyboard.down('Enter')
  assert(await pressed() === 1, 'Accessible focused-key input failed')
  await page.keyboard.up('Enter')
  assert(await pressed() === 0, 'Accessible focused-key release failed')
  add('Focused piano button supports Enter press/release')
  await page.keyboard.down('z')
  await page.evaluate(async () => {
    const analyser = window.__pianoAudio.analysers.find((item) => item.context.state === 'running')
    await analyser.context.suspend()
  })
  await page.getByRole('button', { name: 'Start Piano', exact: true }).waitFor()
  assert(await pressed() === 0, 'Suspended audio context left held notes')
  add('Suspended audio context clears notes and offers restart')
  assert(errors.length === 0, `Runtime errors: ${errors.join(', ')}`)
  return { passed: true, checks, chordRms, silenceRms, sampleRequests: samples, runtimeErrors: errors, userAgent: await page.evaluate(() => navigator.userAgent) }
}
