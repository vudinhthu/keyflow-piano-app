async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message) }
  const pedal = page.getByRole('button', { name: 'Sustain — giữ pedal', exact: true })
  const held = () => page.locator('button[data-note][aria-pressed=true]').count()
  const defocus = () => page.getByRole('heading', { name: 'Salamander Grand' }).click()
  const signal = () => page.evaluate(() => Math.max(0, ...window.__pianoAudio.analysers.map((a) => {
    const v = new Float32Array(a.fftSize)
    a.getFloatTimeDomainData(v)
    return Math.sqrt(v.reduce((sum, x) => sum + x * x, 0) / v.length)
  })))
  await defocus()
  const scrollBefore = await page.evaluate(() => scrollY)
  await page.keyboard.down('Space')
  await page.keyboard.down('z')
  await page.keyboard.up('z')
  await page.waitForTimeout(300)
  const sustainRms = await signal()
  assert(sustainRms > 0.0001 && await held() === 0, 'Keyup did not sustain real audio')
  assert(await pedal.getAttribute('aria-pressed') === 'true', 'Pedal indicator missing')
  assert((await page.locator('.sustain-control').textContent()).includes('1 nốt ngân'), 'Sustained count mismatch')
  assert(await page.evaluate(() => scrollY) === scrollBefore, 'Space scrolled the playing page')
  await page.keyboard.down('c')
  await page.keyboard.up('Space')
  assert(await held() === 1 && await pedal.getAttribute('aria-pressed') === 'false', 'Pedal-up cut held note or stayed on')
  assert((await page.locator('.sustain-control').textContent()).includes('0 nốt ngân'), 'Released sustain stayed in UI')
  await page.keyboard.up('c')
  await page.waitForTimeout(500)
  const releaseRms = await signal()
  assert(releaseRms < 0.000001, 'Pedal release did not reach silence')

  await page.keyboard.down('Space')
  const box = await pedal.boundingBox()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.keyboard.up('Space')
  assert(await pedal.getAttribute('aria-pressed') === 'true', 'Keyboard pedal-up cut pointer-owned pedal')
  await page.mouse.up()
  assert(await pedal.getAttribute('aria-pressed') === 'false', 'Focus-changing keyup left a stuck pedal owner')

  await defocus()
  await page.keyboard.down('Space')
  await page.keyboard.down('z')
  await page.keyboard.up('z')
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  assert(await held() === 0 && await pedal.getAttribute('aria-pressed') === 'false', 'Blur did not reset sustain')
  await page.keyboard.up('Space')
  await page.waitForTimeout(500)
  assert(await signal() < 0.000001, 'Blur left sustained audio')
  await page.getByRole('button', { name: 'Nốt C4, phím Q', exact: true }).focus()
  await page.keyboard.down('Space')
  assert(await held() === 1 && await pedal.getAttribute('aria-pressed') === 'false', 'Focused piano Space also enabled sustain')
  await page.keyboard.up('Space')
  await page.getByRole('slider', { name: 'Âm lượng' }).focus()
  await page.keyboard.press('Space')
  assert(await pedal.getAttribute('aria-pressed') === 'false', 'Sustain intercepted a slider')
  await defocus()
  await page.waitForTimeout(500)
  return { passed: true, sustainRms, releaseRms, checks: ['Keyup sustains real waveform and updates pedal/count', 'Pedal-up releases freed notes while physically held notes survive', 'Keyboard/pointer pedal ownership survives focus-changing keyup', 'Space does not scroll playing area; focused piano buttons and inputs keep native behavior', 'Blur resets pedal/notes to silence'] }
}
