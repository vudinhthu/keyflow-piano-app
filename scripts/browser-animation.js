async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message) }
  const key = page.getByRole('button', { name: 'Nốt C3, phím Z', exact: true })
  await page.getByRole('heading', { name: 'Salamander Grand' }).click()
  const motion = []
  for (const [letter, name] of [['z', 'Nốt C3, phím Z'], ['s', 'Nốt C#3, phím S']]) {
    const pianoKey = page.getByRole('button', { name, exact: true })
    const resting = await pianoKey.boundingBox()
    assert(resting, 'Resting key geometry missing')
    await page.keyboard.down(letter)
    assert(await pianoKey.getAttribute('aria-pressed') === 'true' && (await pianoKey.getAttribute('class')).includes('pressed'), 'Note-on highlight missing')
    await page.waitForTimeout(120)
    const pressed = await pianoKey.boundingBox()
    assert(pressed && pressed.y > resting.y + 1 && pressed.y < resting.y + 4, 'Press animation did not depress the key')
    assert(Math.abs(pressed.x - resting.x) < 0.5 && Math.abs(pressed.width - resting.width) < 0.5, 'Key moved out of its horizontal slot')
    assert(pressed.height < resting.height && pressed.height > resting.height * 0.95, 'Key depression distorted the key height')
    await page.keyboard.up(letter)
    await page.waitForTimeout(120)
    const restored = await pianoKey.boundingBox()
    assert(await pianoKey.getAttribute('aria-pressed') === 'false' && restored && ['x', 'y', 'width', 'height'].every(dimension => Math.abs(restored[dimension] - resting[dimension]) < 0.5), 'Note-off did not restore the key geometry')
    motion.push({ note: name, resting, pressed, restored })
  }
  await page.keyboard.down('Space')
  await page.keyboard.down('z')
  await page.keyboard.up('z')
  assert(await key.getAttribute('data-sustained') === 'true' && await key.getAttribute('aria-pressed') === 'false', 'Sustained note confused with physically held key')
  assert((await key.getAttribute('class')).includes('sustained'), 'Sustain highlight missing')
  await page.screenshot({ path: 'output/playwright/phase2-desktop.png', fullPage: true })
  await page.keyboard.up('Space')
  assert(await key.getAttribute('data-sustained') === 'false', 'Sustain highlight stuck after pedal-up')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const duration = await key.evaluate((node) => getComputedStyle(node).transitionDuration)
  assert(duration.split(',').every((part) => parseFloat(part) === 0), 'Reduced motion retained transition')
  await page.keyboard.down('z')
  assert(await key.getAttribute('aria-pressed') === 'true', 'Reduced motion removed immediate note feedback')
  await page.keyboard.up('z')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.setViewportSize({ width: 390, height: 844 })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Phase 2 toolbar overflowed narrow layout')
  await page.screenshot({ path: 'output/playwright/phase2-narrow.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1100 })
  await page.locator('.orientation-popup').waitFor({ state: 'hidden' })
  await page.waitForTimeout(500)
  return { passed: true, motion, reducedMotionDuration: duration, checks: ['Note-on/off updates correct physical highlight and press/release geometry on white and black keys', 'Released sustained pitches have distinct amber feedback and clear on pedal-up', 'Reduced motion removes transitions while preserving immediate feedback', 'Full toolbar fits desktop and 390 px viewport'] }
}
